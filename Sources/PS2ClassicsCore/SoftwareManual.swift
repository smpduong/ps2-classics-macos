import Foundation
import CoreGraphics
import ImageIO
import PDFKit
import Darwin

/// Native manual generation. Layout follows the pinned pop-fe2 format:
/// USRDIR/CONTENT/manual.idx plus numbered pages: LE width/height + BC1 blocks.
/// The block encoder is original code; no external image tool is required.
public enum SoftwareManual {
    public static let width = 960, height = 768, maximumPages = 100
    public static let pageBytes = 8 + width * height / 2

    /// Encode opaque RGB pixels into standard four-colour BC1 blocks.
    static func encodePage(_ pixels: [UInt8], cancelled: () throws -> Void) throws -> Data {
        guard pixels.count == width * height * 4 else { throw ConversionFailure(message: "Invalid rendered manual page.") }
        var output = Data([0xc0, 0x03, 0, 0, 0, 0x03, 0, 0])
        func rgb(_ colour: UInt16) -> [Int] {
            let r = Int((colour >> 11) & 31), g = Int((colour >> 5) & 63), b = Int(colour & 31)
            return [(r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2)]
        }
        for by in stride(from: 0, to: height, by: 4) {
            try cancelled()
            for bx in stride(from: 0, to: width, by: 4) {
                var colours = [[Int]](); colours.reserveCapacity(16)
                var low = [255,255,255], high = [0,0,0]
                for y in 0..<4 { for x in 0..<4 {
                    let offset = ((by+y)*width+bx+x)*4
                    let c = (0..<3).map { Int(pixels[offset+$0]) }; colours.append(c)
                    for k in 0..<3 { low[k] = min(low[k],c[k]); high[k] = max(high[k],c[k]) }
                } }
                func packed(_ c: [Int]) -> UInt16 { UInt16((c[0] >> 3) << 11 | (c[1] >> 2) << 5 | (c[2] >> 3)) }
                var a = packed(high), b = packed(low)
                if a < b { swap(&a,&b) }
                // Ensure four-colour mode, even for a uniform block.
                if a == b { if a < 65535 { a += 1 } else { b -= 1 } }
                let ca = rgb(a), cb = rgb(b)
                let palette = [ca, cb, (0..<3).map { (2*ca[$0]+cb[$0])/3 }, (0..<3).map { (ca[$0]+2*cb[$0])/3 }]
                var indices: UInt32 = 0
                for (i,c) in colours.enumerated() {
                    let index = (0..<4).min { l,r in
                        (0..<3).reduce(0) { $0 + (c[$1]-palette[l][$1]) * (c[$1]-palette[l][$1]) } <
                        (0..<3).reduce(0) { $0 + (c[$1]-palette[r][$1]) * (c[$1]-palette[r][$1]) }
                    }!
                    indices |= UInt32(index) << (i*2)
                }
                output.append(UInt8(a & 255)); output.append(UInt8(a >> 8))
                output.append(UInt8(b & 255)); output.append(UInt8(b >> 8))
                for i in 0..<4 { output.append(UInt8((indices >> (i*8)) & 255)) }
            }
        }
        return output
    }

    /// Writes only to a new private staging directory owned by PackageBuilder.
    /// Returns hashes of the exact generated bytes for the attempt fingerprint.
    public static func build(source: URL, directory: URL, cancelled: () throws -> Void = {},
                             progress: @escaping @Sendable (ConversionProgress) -> Void = { _ in }) throws -> [String:String] {
        let bytes = try BoundedFile.read(source, maximum: 32 * 1024 * 1024)
        try cancelled()
        let pdf: PDFDocument?
        let image: CGImage?
        if bytes.starts(with: Data("%PDF-".utf8)) {
            guard let document = PDFDocument(data: bytes), !document.isLocked, document.pageCount > 0,
                  document.pageCount <= maximumPages else {
                throw ConversionFailure(message: "Choose an unlocked PDF containing 1–100 pages, up to 32 MB.")
            }
            pdf = document; image = nil
        } else {
            guard let source = CGImageSourceCreateWithData(bytes as CFData, nil),
                  CGImageSourceGetCount(source) == 1,
                  let properties = CGImageSourceCopyPropertiesAtIndex(source,0,nil) as? [CFString:Any],
                  let pixelWidth = properties[kCGImagePropertyPixelWidth] as? NSNumber,
                  let pixelHeight = properties[kCGImagePropertyPixelHeight] as? NSNumber,
                  pixelWidth.doubleValue > 0, pixelHeight.doubleValue > 0,
                  pixelWidth.doubleValue <= 32768, pixelHeight.doubleValue <= 32768,
                  pixelWidth.doubleValue * pixelHeight.doubleValue <= 64_000_000,
                  let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceThumbnailMaxPixelSize: max(width,height),
                    kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary) else {
                throw ConversionFailure(message: "Choose a PDF or a single PNG/JPEG manual page, up to 32 MB; images are limited to 64 megapixels.")
            }
            pdf = nil; image = thumbnail
        }
        guard directory.isFileURL, mkdir(directory.path, 0o700) == 0 else {
            throw ConversionFailure(message: "Manual staging needs a new directory; existing folders are preserved.")
        }
        var complete = false
        defer { if !complete { try? FileManager.default.removeItem(at: directory) } }
        var hashes = [String:String](), names = [String]()
        let count = pdf?.pageCount ?? 1
        for index in 0..<count {
            try cancelled()
            let page = try autoreleasepool { () throws -> Data in
                var pixels = [UInt8](repeating: 255, count: width * height * 4)
                try pixels.withUnsafeMutableBytes { buffer in
                    guard let context = CGContext(data: buffer.baseAddress, width: width, height: height,
                        bitsPerComponent: 8, bytesPerRow: width*4, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                        bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue | CGBitmapInfo.byteOrder32Big.rawValue) else {
                        throw ConversionFailure(message: "Could not render the manual page.")
                    }
                    context.setFillColor(CGColor(gray: 1, alpha: 1))
                    context.fill(CGRect(x: 0, y: 0, width: width, height: height))
                    context.interpolationQuality = .high
                    if let pdf, let pdfPage = pdf.page(at: index), let page = pdfPage.pageRef {
                        let bounds = CGRect(x: 0, y: 0, width: width, height: height)
                        context.concatenate(page.getDrawingTransform(.mediaBox, rect: bounds, rotate: 0, preserveAspectRatio: true))
                        context.drawPDFPage(page)
                    } else if let image {
                        let scale = min(Double(width)/Double(image.width), Double(height)/Double(image.height))
                        let w = Double(image.width)*scale, h = Double(image.height)*scale
                        context.draw(image, in: CGRect(x:(Double(width)-w)/2,y:(Double(height)-h)/2,width:w,height:h))
                    } else { throw ConversionFailure(message: "A manual page could not be read.") }
                }
                return try encodePage(pixels, cancelled: cancelled)
            }
            let name = String(format: "%03d.dxt", index+1)
            try page.write(to: directory.appendingPathComponent(name), options: .withoutOverwriting)
            hashes["manual/"+name] = FileDigest.sha256(data: page); names.append(name)
            progress(ConversionProgress(stage: "Preparing manual page \(index+1) of \(count)", fraction: Double(index+1)/Double(count)))
        }
        let index = Data((names.joined(separator: "\n")+"\n").utf8)
        try index.write(to: directory.appendingPathComponent("manual.idx"), options: .withoutOverwriting)
        hashes["manual/index"] = FileDigest.sha256(data: index)
        try cancelled(); complete = true
        return hashes
    }
}
